#include <stdio.h>
#include <string.h>

static const unsigned char enc[] = { 0x12, 0x1c, 0x32, 0x21, 0x29, 0x3b, 0x41, 0x58, 0x45, 0x46, 0x49, 0x56, 0x29, 0xc0, 0xd0, 0xc4, 0xc2 };
static const unsigned char blob[] = { 0x74, 0x66, 0x7b, 0x43, 0x5b, 0x41, 0x5b, 0x4b, 0x6b, 0x72, 0x60, 0x6e, 0x54, 0x15, 0x1e, 0x11, 0x17, 0x03, 0x1f, 0x0d, 0x0c, 0x2c, 0x3c, 0x32, 0x2a, 0x2b, 0xd9, 0xc3, 0xe4, 0xc7, 0xcd, 0xc0, 0xea };

int main(void) {
    char in[96];
    printf("Enter license key: ");
    if (!fgets(in, sizeof in, stdin)) return 1;
    in[strcspn(in, "\r\n")] = 0;

    size_t n = sizeof enc;
    if (strlen(in) != n) { puts("Invalid license."); return 1; }
    for (size_t i = 0; i < n; i++) {
        if ((unsigned char)(in[i] ^ (0x5A + i * 3)) != enc[i]) { puts("Invalid license."); return 1; }
    }
    printf("License valid. Your reward: ");
    for (size_t j = 0; j < sizeof blob; j++) putchar(blob[j] ^ 0x37 ^ (unsigned char)(j * 5));
    putchar('\n');
    return 0;
}
